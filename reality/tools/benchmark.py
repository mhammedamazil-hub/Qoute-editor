"""Benchmark the pure-Python solver kernels and write reality/PERFORMANCE_REPORT.md.

Usage (from the repository root):
    PYTHONPATH=reality/src python reality/tools/benchmark.py

Timings are wall-clock medians over repeats on the machine that runs this script. They are
a baseline for later C++/GPU work, not a claim of production performance.
"""

from __future__ import annotations

import datetime
import math
import os
import pathlib
import platform
import statistics
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from reality import mechanics as M  # noqa: E402
from reality.integrators import integrate_rk4  # noqa: E402
from reality import thermal as T  # noqa: E402
from reality import validation as V  # noqa: E402


def _median_time(fn, repeats: int = 5) -> float:
    times = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        fn()
        times.append(time.perf_counter() - t0)
    return statistics.median(times)


def bench_orbit_verlet():
    steps = 20000
    dt = 5e-3
    secs = _median_time(lambda: M.kepler_orbit_verlet(1.0, [1.0, 0.0], [0.0, 1.2], dt, steps))
    return ("Kepler orbit, velocity Verlet", steps, secs)


def bench_pendulum_rk4():
    steps = 5000
    dt = 2e-3
    def f(_t, y):
        return [y[1], -math.sin(y[0])]

    secs = _median_time(lambda: integrate_rk4(f, 0.0, [1.0, 0.0], steps * dt, dt))
    return ("Pendulum, classical RK4", steps, secs)


def bench_conduction(n_cells: int):
    alpha, dx = 1.2e-5, 0.1 / (n_cells - 1)
    dt = 0.4 * dx * dx / alpha
    steps = 200
    init = [300.0] * n_cells
    secs = _median_time(lambda: T.conduction_1d_explicit(init, alpha, dx, dt, steps, 500.0, 500.0), repeats=3)
    return (f"1D FTCS conduction, {n_cells} cells", steps * n_cells, secs)


def bench_validation_suite():
    secs = _median_time(lambda: V.run_all(), repeats=3)
    return ("Full validation suite", len(V.CASES), secs)


def _cpu_model() -> str:
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as fh:
            for line in fh:
                if line.lower().startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def build_report() -> str:
    rows = [
        bench_orbit_verlet(),
        bench_pendulum_rk4(),
        bench_conduction(101),
        bench_conduction(1001),
        bench_validation_suite(),
    ]
    lines = []
    w = lines.append
    w("# PERFORMANCE REPORT - PROJECT REALITY")
    w("")
    w("> Generated by `reality/tools/benchmark.py`. Re-run the tool to refresh.")
    w("")
    w(f"- Generated: {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    w(f"- Python: {platform.python_version()}, CPU: {_cpu_model()}, logical cores: {os.cpu_count()}")
    w("- Method: median wall-clock time over repeats (5 for solvers, 3 for the conduction and suite benchmarks).")
    w("")
    w("## Baseline throughput")
    w("")
    w("| Workload | Work units | Median time (s) | Throughput (units/s) | Time per unit (us) |")
    w("|---|---:|---:|---:|---:|")
    for name, units, secs in rows:
        w(f"| {name} | {units} | {secs:.4f} | {units / secs:,.0f} | {1e6 * secs / units:.2f} |")
    w("")
    w("## Interpretation")
    w("")
    w("- These numbers come from pure, dependency-free Python, which is the reference implementation.")
    w("  They establish a correctness baseline and a scaling baseline; they are not a performance claim.")
    w("- Arithmetic for a 60 FPS scene: 10^4 updates per frame needs 6 x 10^5 updates/s and 10^6 needs")
    w("  6 x 10^7 updates/s. The measured kernels above run at roughly 10^5 to 10^7 simple updates/s on this")
    w("  machine, so pure Python covers small scenes only. Larger scenes need C++ (in-Blender) or GPU")
    w("  kernels; the porting order is listed in `ARCHITECTURE.md`.")
    w("- Adaptive or multi-resolution methods and GPU backends are not implemented; no speed-up is claimed.")
    w("- Accuracy/performance trade-offs are expressed through explicit step sizes and tolerances")
    w("  (see `NUMERICAL_METHODS.md`). Shrinking `dt` buys accuracy at a known cost, never silently.")
    w("")
    return "\n".join(lines)


def main() -> int:
    report = build_report()
    out = ROOT / "PERFORMANCE_REPORT.md"
    out.write_text(report, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
