"""Run every scientific validation case and regenerate reality/VALIDATION_REPORT.md.

Usage (from the repository root):
    PYTHONPATH=reality/src python reality/tools/run_validation.py
"""

from __future__ import annotations

import datetime
import pathlib
import platform
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from reality import validation as V  # noqa: E402


def _fmt(x: float) -> str:
    if x == 0:
        return "0"
    return f"{x:.3e}"


def build_report() -> str:
    results = V.run_all()
    n_pass = sum(1 for *_, ok in results if ok)
    n_total = len(results)
    lines = []
    w = lines.append
    w("# VALIDATION REPORT - PROJECT REALITY")
    w("")
    w("> Generated by `reality/tools/run_validation.py`. Do not edit by hand; re-run the tool.")
    w("")
    w(f"- Generated: {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    w(f"- Python: {platform.python_version()} ({platform.machine()}), no third-party numeric libraries")
    w(f"- Cases passed: **{n_pass} / {n_total}**")
    w("")
    w("## How to read this report")
    w("")
    w("Each case compares a solver with a reference: an analytic closed form, a textbook result,")
    w("a separate numerical method, or a conservation law. *Measured error* is the relative error")
    w("(absolute error when the reference is 0). A case passes when the error is below its tolerance.")
    w("")
    w("Kinds of check:")
    w("")
    w("- `analytic` / `textbook`: solver output vs closed-form or published value.")
    w("- `numerical-vs-analytic`: time-stepping or discretised solver vs exact solution.")
    w("- `conservation`: an invariant (momentum, energy, angular momentum, Stefan balance) is preserved.")
    w("- `database`: data-integrity checks on the material database.")
    w("")
    w("Some `analytic` cases verify algebra (for example an identity such as R + T = 1). They confirm")
    w("the implementation of a formula, not that the formula describes a real system. Physical")
    w("validity still depends on the model assumptions listed in `PHYSICS_MODELS.md` and `LIMITATIONS.md`.")
    w("")
    w("## Summary by domain")
    w("")
    w("| Domain | Cases | Passed |")
    w("|---|---:|---:|")
    domains = {}
    for case, _m, _e, ok in results:
        d = domains.setdefault(case.domain, [0, 0])
        d[0] += 1
        d[1] += int(ok)
    for dom, (tot, ok) in domains.items():
        w(f"| {dom} | {tot} | {ok} |")
    w("")
    w("## Results")
    w("")
    w("| ID | Domain | Solver | Check | Kind | Reference source | Reference | Measured | Error | Tolerance | Status |")
    w("|---|---|---|---|---|---|---:|---:|---:|---:|---|")
    for case, measured, err, ok in results:
        ref = "0" if case.reference == 0 else f"{case.reference:g}"
        w(
            f"| {case.case_id} | {case.domain} | {case.solver} | {case.description} | {case.kind} | "
            f"{case.reference_source} | {ref} | {_fmt(measured)} | {_fmt(err)} | {case.tolerance:g} | "
            f"{'PASS' if ok else '**FAIL**'} |"
        )
    w("")
    w("## Solver validation status")
    w("")
    w("A solver passes only when all of its cases pass. Status below is computed from the table above.")
    w("")
    w("| Solver | Cases | Status |")
    w("|---|---:|---|")
    solvers = {}
    for case, _m, _e, ok in results:
        s = solvers.setdefault(case.solver, [0, True])
        s[0] += 1
        s[1] = s[1] and ok
    for solver, (tot, ok) in sorted(solvers.items()):
        w(f"| {solver} | {tot} | {'passes all in-repo references (no experimental data yet)' if ok else 'NOT VALIDATED'} |")
    w("")
    w("## Known validation gaps")
    w("")
    w("- No comparison yet against measured laboratory experiments (drop tests, Hertz contact, fracture")
    w("  specimens, acoustic chambers). Those reference datasets are planned in `DEVELOPMENT_ROADMAP.md`.")
    w("- Material property values are representative handbook figures; each carries an uncertainty note in")
    w("  `MATERIAL_DATABASE.md`. Validation checks the code, not the accuracy of every input value.")
    w("- Cross-solver tests (for example, heat flowing from a hot body into a fracturing body) are not yet built.")
    w("")
    return "\n".join(lines)


def main() -> int:
    report = build_report()
    out = ROOT / "VALIDATION_REPORT.md"
    out.write_text(report, encoding="utf-8")
    results = V.run_all()
    failed = [case.case_id for case, _measured, _err, ok in results if not ok]
    print(f"wrote {out} ({len(results)} cases, {len(failed)} failing)")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
