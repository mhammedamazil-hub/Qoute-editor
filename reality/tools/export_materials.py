"""Generate reality/MATERIAL_DATABASE.md from the in-code material database.

Usage (from the repository root):
    PYTHONPATH=reality/src python reality/tools/export_materials.py
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from reality.materials import default_database  # noqa: E402


def _fmt(v, scale=1.0, digits=4):
    if v is None:
        return "-"
    x = v / scale
    if abs(x) >= 1e4 or (abs(x) < 1e-2 and x != 0):
        return f"{x:.3g}"
    return f"{x:.{digits}g}"


def build() -> str:
    db = default_database()
    out = []
    w = out.append
    w("# MATERIAL_DATABASE - PROJECT REALITY")
    w("")
    w("> Generated by `reality/tools/export_materials.py` from `reality/src/reality/materials.py`.")
    w("> Edit the data in code, then re-run the tool. Values are SI unless stated.")
    w("")
    w("## Purpose and rules")
    w("")
    w("- Each material is a physical object description, not a shader. It holds properties that the solvers need.")
    w("- A property is `-` when it does not apply (for example, the Young's modulus of water).")
    w("- Friction and restitution are **not** stored here. They belong to a contact pair, not to one material.")
    w("- Every entry cites a source and states its uncertainty. Values are representative handbook figures, not")
    w("  certified measurements. They must be re-checked against the cited edition before a scientific claim.")
    w("- Custom materials are added at run time with `MaterialDatabase.add()`. The same validation rules apply.")
    w("")
    w("## Units")
    w("")
    w("| Column | Unit |")
    w("|---|---|")
    w("| density | kg/m^3 |")
    w("| E (Young's modulus), yield, tensile | GPa, MPa (as labelled) |")
    w("| K_Ic | MPa*sqrt(m) |")
    w("| c_p | J/(kg K) |")
    w("| k | W/(m K) |")
    w("| T_melt | K |")
    w("| L_f | kJ/kg |")
    w("| mu (dynamic viscosity) | mPa*s |")
    w("| n | dimensionless refractive index (589 nm unless the source says otherwise) |")
    w("")
    w("## Summary table")
    w("")
    w("| Material | Category | Phase | Behaviour | rho | E (GPa) | nu | sigma_y (MPa) | sigma_t (MPa) | K_Ic (MPa√m) | c_p | k | T_melt (K) | L_f (kJ/kg) | mu (mPa·s) | n |")
    w("|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for m in db:
        w(
            f"| {m.name} | {m.category} | {m.phase} | {m.behavior} | {_fmt(m.density)} | "
            f"{_fmt(m.youngs_modulus, 1e9)} | {_fmt(m.poisson_ratio)} | {_fmt(m.yield_strength, 1e6)} | "
            f"{_fmt(m.tensile_strength, 1e6)} | {_fmt(m.fracture_toughness, 1e6)} | {_fmt(m.specific_heat)} | "
            f"{_fmt(m.thermal_conductivity)} | {_fmt(m.melting_temperature)} | {_fmt(m.latent_heat_fusion, 1e3)} | "
            f"{_fmt(m.dynamic_viscosity, 1e-3)} | {_fmt(m.refractive_index)} |"
        )
    w("")
    w("## Entries: source and uncertainty")
    w("")
    for m in db:
        w(f"### {m.name}")
        w("")
        w(f"- **Category / phase / behaviour:** {m.category} / {m.phase} / {m.behavior}")
        w(f"- **Source:** {m.source}")
        w(f"- **Uncertainty:** {m.uncertainty}")
        if m.notes:
            w(f"- **Notes:** {m.notes}")
        w("")
    w("## Electrical conductivity")
    w("")
    w("Stored for the metals only (S/m, from the CRC Handbook at 20 degC): " + ", ".join(
        f"{m.name} {m.electrical_conductivity:.3g}" for m in db if m.electrical_conductivity is not None) + ".")
    w("No solver uses this property yet.")
    w("")
    return "\n".join(out)


def main() -> int:
    path = ROOT / "MATERIAL_DATABASE.md"
    path.write_text(build(), encoding="utf-8")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
