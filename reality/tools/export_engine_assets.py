"""Generate the engine's shared data from the Python kernel (single source of truth).

Writes two kinds of file under ``engine/``:

- ``engine/src/physics/materials.generated.ts``: material densities from ``materials.default_database()``;
- ``engine/test/fixtures/<scene>.json``: reference trajectories from ``control.simulate.run`` for every scene in
  ``engine/public/scenes``. The TypeScript tests compare the browser physics against these.

Run from the repository root:  PYTHONPATH=reality/src python3 reality/tools/export_engine_assets.py
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ENGINE = ROOT / "engine"
FIXTURE_DT = 1e-4          # the same step the Python kernel uses by default
FIXTURE_RECORD = 0.01      # seconds between recorded samples
FIXTURE_DURATION = {"rolling-sphere": 1.0, "bouncing-sphere": 2.0, "ramp-roll": 1.0}


def write_materials() -> int:
    from reality.materials import default_database

    db = default_database()
    names = db.names()
    lines = [
        "// Generated by reality/tools/export_engine_assets.py from reality.materials.default_database().",
        "// Do not edit by hand. Densities in kg/m^3; see reality/MATERIAL_DATABASE.md for sources.",
        "export const MATERIAL_DENSITY_KG_M3: Readonly<Record<string, number>> = {",
    ]
    for name in names:
        lines.append(f"  {json.dumps(name)}: {repr(float(db.get(name).density))},")
    lines += ["};", ""]
    out = ENGINE / "src" / "physics" / "materials.generated.ts"
    out.write_text("\n".join(lines), encoding="utf-8")
    return len(names)


def write_fixtures() -> list:
    from reality.control import simulate as SIM

    written = []
    for name, duration in FIXTURE_DURATION.items():
        scene = json.loads((ENGINE / "public" / "scenes" / f"{name}.json").read_text(encoding="utf-8"))
        result = SIM.run(scene, duration, dt=FIXTURE_DT, record_interval=FIXTURE_RECORD)
        body_id = scene["bodies"][0]["id"]
        records = []
        for rec in result["records"]:
            b = rec["bodies"][body_id]
            records.append({
                "t": rec["t"],
                "position": b["position"],
                "velocity": b["velocity"],
                "quaternion": b["quaternion"],
                "omega_body": b["omega_body"],
            })
        doc = {
            "source": "reality.control.simulate.run",
            "reality_version": result["software"]["version"],
            "scene_sha256": result["scene_sha256"],
            "dt": FIXTURE_DT,
            "duration": duration,
            "record_interval": FIXTURE_RECORD,
            "scene": scene,
            "records": records,
        }
        path = ENGINE / "test" / "fixtures" / f"{name}.json"
        path.write_text(json.dumps(doc, indent=1, allow_nan=False) + "\n", encoding="utf-8")
        written.append((name, len(records)))
    return written


def main() -> int:
    n = write_materials()
    print(f"materials.generated.ts: {n} materials")
    for name, count in write_fixtures():
        print(f"fixtures/{name}.json: {count} records")
    return 0


if __name__ == "__main__":
    sys.exit(main())
