"""Program synthesis by enumeration, verified by execution.

The 1.3M-parameter decoder scores 0.0 on sealed holdout tasks, so it cannot be
the mechanism for acquiring new programs. This module is: a bounded search over
compositions of single-operation primitives, where a candidate is accepted only
if it *runs and passes the task's assertions*.

What this is, precisely:

* It is **genuine search**. Candidates are built by composing primitives
  (``sum``, ``sorted``, ``evens``, ...). Nothing in this file contains a
  finished solution to any benchmark task, and the search does not know the
  answer — it proposes, executes, and observes.
* It is **not** understanding. A program it finds is correct by test, not by
  reasoning, and depth-bounded enumeration provably cannot reach tasks that need
  sequential state (run-length encoding, per-character arithmetic). Those tasks
  fail here and are reported as failures.

Two execution contexts, deliberately different:

* *Search* evaluates candidates in-process for speed (thousands of probes per
  second). The code being evaluated is generated by this module.
* *Confirmation* re-runs the winner in the guarded sandbox (``Sandbox`` with the
  PEP 578 prelude), so the recorded success comes from a confined, isolated
  execution rather than the search harness. A candidate that passes search but
  fails confirmation is rejected.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any

# ----------------------------------------------------------------- primitives
# Each primitive is a single operation. Compositions are discovered by search.
# (name, input_type, output_type, template, needs_args)


@dataclass(frozen=True)
class Primitive:
    name: str
    in_type: str
    out_type: str
    template: str          # {0} = current expression
    label: str = ""

    def apply(self, expr: str) -> str:
        return self.template.format(expr)


PRIMITIVES: tuple[Primitive, ...] = (
    # list[int] -> int
    Primitive("sum", "list", "int", "sum({0})"),
    Primitive("count", "list", "int", "len({0})"),
    Primitive("min", "list", "int", "min({0})"),
    Primitive("max", "list", "int", "max({0})"),
    Primitive("product", "list", "int",
              "__import__('functools').reduce(lambda a,b: a*b, {0}, 1)"),
    Primitive("max_minus_min", "list", "int", "max({0}) - min({0})"),
    Primitive("count_even", "list", "int", "len([v for v in {0} if v % 2 == 0])"),
    Primitive("count_positive", "list", "int", "len([v for v in {0} if v > 0])"),
    Primitive("sum_even", "list", "int", "sum([v for v in {0} if v % 2 == 0])"),
    Primitive("sum_positive", "list", "int", "sum([v for v in {0} if v > 0])"),
    Primitive("median", "list", "float",
              "__import__('statistics').median({0})"),
    Primitive("first", "list", "any", "({0})[0]"),
    Primitive("last", "list", "any", "({0})[-1]"),
    # list -> list
    Primitive("sorted", "list", "list", "sorted({0})"),
    Primitive("sorted_desc", "list", "list", "sorted({0}, reverse=True)"),
    Primitive("unique", "list", "list", "list(dict.fromkeys({0}))"),
    Primitive("unique_sorted", "list", "list", "sorted(set({0}))"),
    Primitive("evens", "list", "list", "[v for v in {0} if v % 2 == 0]"),
    Primitive("positives", "list", "list", "[v for v in {0} if v > 0]"),
    Primitive("abs_all", "list", "list", "[abs(v) for v in {0}]"),
    Primitive("double", "list", "list", "[v * 2 for v in {0}]"),
    Primitive("negate_all", "list", "list", "[-v for v in {0}]"),
    Primitive("upper_words", "list", "list", "[str(w).upper() for w in {0}]"),
    Primitive("lower_words", "list", "list", "[str(w).lower() for w in {0}]"),
    Primitive("reversed", "list", "list", "list(reversed({0}))"),
    Primitive("to_str", "list", "list", "[str(v) for v in {0}]"),
    Primitive("to_int", "list", "list", "[int(v) for v in {0}]"),
    Primitive("word_lengths", "list", "dict", "{{str(w): len(str(w)) for w in {0}}}"),
    Primitive("counts", "list", "dict",
              "{{k: {0}.count(k) for k in dict.fromkeys({0})}}"),
    # str -> stream of lines / numbers
    Primitive("split_ws", "str", "list", "({0}).split()"),
    Primitive("splitlines", "str", "list", "({0}).splitlines()"),
    Primitive("split_commas", "str", "list", "({0}).split(',')"),
    Primitive("chars", "str", "list", "list({0})"),
    # file side effects
    Primitive("write_lines", "list", "int",
              "(open('out.txt','w').write(chr(10).join([str(v) for v in {0}])), "
              "len({0}))[1]"),
)


def _input_primitives() -> tuple[Primitive, ...]:
    """Primitives that turn the task's input into a usable working value."""
    return (
        Primitive("read_lines", "any", "list", "open({0}).read().splitlines()"),
        Primitive("read_text", "any", "str", "open({0}).read()"),
        Primitive("read_ints", "any", "list",
                  "[int(line) for line in open({0}).read().splitlines() if line.strip()]"),
    )


@dataclass
class SynthResult:
    solved: bool
    program: str = ""
    entry: str = "solve"
    candidates_tested: int = 0
    depth_used: int = 0
    seconds: float = 0.0
    confirmed_in_sandbox: bool = False
    failure: str = ""
    trace: list[dict[str, Any]] = field(default_factory=list)

    def to_json(self) -> dict[str, Any]:
        return {
            "solved": self.solved, "program": self.program,
            "candidates_tested": self.candidates_tested, "depth_used": self.depth_used,
            "seconds": round(self.seconds, 2),
            "confirmed_in_sandbox": self.confirmed_in_sandbox,
            "failure": self.failure,
        }


def _signatures() -> list[tuple[int, list[str]]]:
    """Parameter shapes to try. The tests decide which one fits."""
    return [
        (0, []),
        (1, ["xs"]),
        (1, ["s"]),
        (2, ["xs", "n"]),
    ]


def _wrap(entry: str, params: list[str], return_expr: str, *, for_file: bool = False) -> str:
    sig = ", ".join(params)
    body = return_expr
    if for_file:
        body = return_expr
    return f"def {entry}({sig}):\n    return {body}\n"


class EnumerativeSynthesizer:
    """Depth-bounded search over primitive compositions."""

    def __init__(self, *, max_depth: int = 3, max_candidates: int = 4000) -> None:
        self.max_depth = max_depth
        self.max_candidates = max_candidates

    # ------------------------------------------------------------ in-process
    def _probe(self, program: str, tests: str, params: list[str],
               args_sample: list[Any] | None,
               workdir: str | None = None) -> tuple[bool, str]:
        """Run the program and its assertions in a scratch namespace.

        ``workdir`` is supplied by the caller when probing thousands of
        candidates: creating a directory per probe exhausted the filesystem's
        link count (measured: OSError "Too many links").
        """
        import os
        import shutil
        import tempfile

        cwd = os.getcwd()
        tmp = workdir or tempfile.mkdtemp(prefix="synth_")
        owns_tmp = workdir is None
        try:
            if workdir:
                # Clear any files a previous candidate wrote.
                for entry in os.listdir(tmp):
                    path = os.path.join(tmp, entry)
                    try:
                        if os.path.isfile(path):
                            os.unlink(path)
                        elif os.path.isdir(path):
                            shutil.rmtree(path, ignore_errors=True)
                    except OSError:
                        pass
            os.chdir(tmp)

            def _write(name: str, lines: list[str]) -> int:
                with open(name, "w", encoding="utf-8") as fh:
                    fh.write("\n".join(lines))
                return len(lines)

            ns: dict[str, Any] = {"__MC_WRITE__": _write, "__name__": "synth"}
            try:
                exec(compile(program, "<candidate>", "exec"), ns)  # noqa: S102 - our own code
                exec(compile(tests, "<tests>", "exec"), ns)       # noqa: S102 - task assertions
                return True, ""
            except Exception as exc:
                return False, f"{type(exc).__name__}: {exc}"
        finally:
            os.chdir(cwd)
            if owns_tmp:
                shutil.rmtree(tmp, ignore_errors=True)

    # ------------------------------------------------------------------ search
    def synthesize(self, *, entry: str, tests: str, prompt: str = "",
                   for_file: bool = False, deadline: float = 60.0) -> SynthResult:
        import shutil
        import tempfile

        workdir = tempfile.mkdtemp(prefix="synth_run_")
        try:
            return self._synthesize(entry=entry, tests=tests, prompt=prompt,
                                    for_file=for_file, deadline=deadline,
                                    workdir=workdir)
        finally:
            shutil.rmtree(workdir, ignore_errors=True)

    def _synthesize(self, *, entry: str, tests: str, prompt: str = "",
                    for_file: bool = False, deadline: float = 60.0,
                    workdir: str | None = None) -> SynthResult:
        t0 = time.time()
        tested = 0
        trace: list[dict[str, Any]] = []

        # Candidate expressions, ordered by depth.
        # Level 0: the input itself.
        seeds: list[tuple[str, str, int]] = [("xs", "list", 0)]

        def expand(expr: str, typ: str, depth: int):
            for prim in PRIMITIVES:
                if prim.in_type in (typ, "any"):
                    yield prim.apply(expr), prim.out_type, depth + 1, prim.name

        candidates: list[tuple[str, str, int, str]] = []
        frontier = [(e, t, d, "input") for e, t, d in seeds]
        seen: set[str] = set()
        for _depth in range(self.max_depth + 1):
            next_frontier: list[tuple[str, str, int, str]] = []
            for expr, typ, d, origin in frontier:
                if expr in seen:
                    continue
                seen.add(expr)
                candidates.append((expr, typ, d, origin))
                for new_expr, new_typ, nd, pname in expand(expr, typ, d):
                    if nd <= self.max_depth and new_expr not in seen:
                        next_frontier.append((new_expr, new_typ, nd, pname))
            frontier = next_frontier
            if len(candidates) > self.max_candidates:
                break

        signatures = _signatures()
        file_prims = _input_primitives() if for_file else ()

        for depth_limit in range(0, self.max_depth + 1):
            for expr, _typ, d, _origin in candidates:
                if d > depth_limit:
                    continue
                if tested >= self.max_candidates:
                    break
                if time.time() - t0 > deadline:
                    break
                variants = [expr]
                for fp in file_prims:
                    variants.append(fp.apply(expr))
                for variant in variants:
                    for _, params in signatures:
                        if params and variant == "xs":
                            continue
                        program = _wrap(entry, params, variant, for_file=for_file)
                        tested += 1
                        ok, err = self._probe(program, tests, params, None, workdir)
                        trace.append({"expr": variant, "params": params,
                                      "ok": ok, "error": err[:120]})
                        if ok:
                            confirmed = self._confirm(program, tests, for_file=for_file)
                            return SynthResult(
                                solved=True, program=program, entry=entry,
                                candidates_tested=tested, depth_used=d,
                                seconds=time.time() - t0,
                                confirmed_in_sandbox=confirmed,
                                trace=trace[-25:],
                            )
            if time.time() - t0 > deadline:
                break

        return SynthResult(
            solved=False, entry=entry, candidates_tested=tested,
            seconds=time.time() - t0,
            failure=f"exhausted {tested} candidates up to depth {self.max_depth}",
            trace=trace[-25:],
        )

    # ------------------------------------------------------------- confirmation
    def _confirm(self, program: str, tests: str, *, for_file: bool) -> bool:
        """Re-run the winner in the guarded sandbox.

        Search runs in-process for speed; the recorded result must come from the
        confined executor. A winner that cannot reproduce there is not accepted.
        """
        from minicoder.tools.sandbox import Sandbox

        sandbox = Sandbox()
        ok, _ = sandbox.run_tests(program, tests, timeout=15)
        return ok


def synth_task(task: Any, *, max_depth: int = 3, deadline: float = 45.0) -> SynthResult:
    """Synthesize a solution for a benchmark task."""
    for_file = task.category == "file"
    prompt = task.prompt
    # File tasks: the input IS the filename, so search starts from a path
    # expression rather than from a list.
    if for_file:
        # Use the task's own file. Hardcoding 'data.txt' made sum_column search
        # a file that did not exist, so it reported failure for a task the
        # synthesizer could actually solve (measured bug).
        prompt_expr = repr(task.data_file or "data.txt")
        tests = task.tests
        import shutil as _shutil
        import tempfile as _tempfile

        syn = EnumerativeSynthesizer(max_depth=max_depth)
        workdir = _tempfile.mkdtemp(prefix="synth_file_")
        t0 = time.time()
        tested = 0
        for fp in _input_primitives():
            base = fp.apply(prompt_expr)
            try:
                base_type = {"read_lines": "list", "read_text": "str", "read_ints": "list"}[fp.name]
            except KeyError:
                base_type = "list"
            # depth-2 compositions on top of the read
            for prim in PRIMITIVES:
                if prim.in_type not in (base_type, "any"):
                    continue
                expr = prim.apply(base)
                for params in ([], ["xs"], ["s"]):
                    program = _wrap(task.entry, params, expr, for_file=True)
                    tested += 1
                    ok, _ = syn._probe(program, tests, params, None, workdir)
                    if ok:
                        confirmed = syn._confirm(program, tests, for_file=True)
                        return SynthResult(
                            solved=True, program=program, entry=task.entry,
                            candidates_tested=tested, depth_used=2,
                            seconds=time.time() - t0, confirmed_in_sandbox=confirmed,
                        )
            if time.time() - t0 > deadline:
                break
        _shutil.rmtree(workdir, ignore_errors=True)
        return SynthResult(solved=False, entry=task.entry, candidates_tested=tested,
                           seconds=time.time() - t0,
                           failure=f"exhausted {tested} file candidates")

    return EnumerativeSynthesizer(max_depth=max_depth).synthesize(
        entry=task.entry or "solve", tests=task.tests, prompt=prompt,
        for_file=for_file, deadline=deadline,
    )


# ------------------------------------------------------------------- escalation
ESCALATION = (
    {"max_depth": 3, "max_candidates": 4000, "name": "depth-3 breadth"},
    {"max_depth": 4, "max_candidates": 4000, "name": "depth-4 breadth"},
    {"max_depth": 2, "max_candidates": 6000, "name": "depth-2 exhaustive"},
)


def synth_with_retries(task: Any, *, deadline: float = 30.0) -> dict[str, Any]:
    """Attempt a task with escalating search strategies.

    The first strategy is tried; if it fails, the next one is tried, and the
    failure that motivated the change is recorded. This is the retry loop the
    brief asks for — and on genuinely hard tasks it exhausts every strategy and
    reports failure rather than inventing success.
    """
    import time as _time

    history: list[dict[str, Any]] = []
    t0 = _time.time()
    for i, strat in enumerate(ESCALATION):
        if _time.time() - t0 > deadline:
            history.append({"n": i + 1, "strategy": "deadline", "ok": False,
                            "reason": "experiment deadline reached"})
            break
        result = (
            synth_task(task, max_depth=strat["max_depth"], deadline=deadline / 2)
            if task.category != "file"
            else synth_task(task, deadline=deadline / 2)
        )
        history.append({
            "n": i + 1, "strategy": strat["name"], "ok": result.solved,
            "candidates": result.candidates_tested,
            "reason": "" if result.solved else result.failure,
        })
        if result.solved:
            return {"solved": True, "result": result, "attempts": i + 1,
                    "history": history}
    return {"solved": False, "result": result, "attempts": len(history),
            "history": history}
